      <p class="p">字幕设置和评论排版均提供「配色预设」，内置 16 款，按活力暖色、清新梦幻、浅景深字、柔和中性筛选。色卡同时示意浅深背景，悬停可看色值和设计理由；「暖象牙」保留柔和旧配色。选择只替换文字和描边颜色，不改粗细、底色、字号或时间，进入草稿后按原有按钮保存；手动调色会显示为自定义。全部色对的亮度对比 ≥ 7:1，但不代表在运动视频上自动达标，细字、关闭描边或复杂画面仍须检查实际预览。</p>
      <p class="p">确认方案不会自动生成视频。在「合成成片」中为相应版本开启「叠加评论」后才会使用；原声评论版不需要配音或对话字幕。每种版本独立选择是否叠加，试片使用当前版本设置，均按原视频时间轴显示。超出视频结尾的评论不显示。任务提交后使用已冻结的方案，后续修改不影响在途合成；重新抓取评论也不会覆盖已确认的上屏文字。</p>
