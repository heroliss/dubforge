        <n-collapse-item title="翻译为什么会分块？怎么估算块数？" name="translatechunks">
          <p class="p">
            DubForge 会先扣除系统提示词、术语表和输出预留，再按字幕行的估算 token 数装入每个整体翻译窗口；默认还限制每窗最多 100 条字幕行，避免服务商容量很大时单次响应过慢。
            token 预算优先，100 行只是安全上限，实际窗口可能更小；将“单次最多字幕行数”设为 0 可关闭行数限制。同样 80 行字幕，短句可能一块，很长的中英文混排也可能多块；日志会显示总预算、正文预算和最终窗口数。
            每个窗口一次完成上下文理解和逐行翻译；只有超出 token 预算或行数安全上限才开新窗口，不再额外执行两步直译或全局审校。
            请求与局部修复都附上每句时长，引导译文在自然语速下说完，短句尽量简洁且保留关键信息；实际语音时长仍以合成结果为准。
            可在“风格提示词”中说明人设和表达偏好，支持方言、幽默、网络流行语等润色与本地化；留空时采用贴近原语气的自然口语。提示词提供任务背景、纠错和衔接建议，具体表达交给模型判断。
            模型逐行返回“行号. 译文”，句子数量、标号及顺序与原文一致，每句译文非空；风格润色在各句内进行，不合并、拆分或省略句子。DubForge 兼容编号空格、多余空白行等格式差异；缺句或空译文只补齐问题句，相邻句仅供参考；无编号文本、未知号、重复号或乱序可能造成连续错位，会重新翻译整个窗口。多窗口按顺序处理，中间窗口末尾携带简短交接摘要。重试仍失败则报告失败，不接受空译文作为成功结果。
          </p>
        </n-collapse-item>
        <n-collapse-item title="转录和语义整理为什么分成两步？句子会不会太碎？" name="splitdesign">
          <p class="p">
            转录阶段的首要任务是识别文字并保存<strong>词级时间戳</strong>，因此先按明显停顿、强句末标点或约 2 秒的识别后短语上限形成时间锚点，
            这一步不会把音频切成 2 秒小块，Whisper 仍保留自己的识别上下文。词级原始结果保存在 words.json 中，保留识别器返回的浮点秒数；发给 LLM 时显示为 0.01 秒精度，最终 SRT 仍写到 0.001 秒。逗号、分号等标点会先形成短语锚点，但不代表最终字幕一定要在这里断开。语义整理阶段可按设置选择只发送短语时间轴，或发送全部词级时间信息，并附上停顿提示；模型根据语义、停顿、字符数和时间戳
            自主决定合并或拆分，并为结果分配时间范围；目标长度和时长允许适度超过，明显过长时再按自然边界细分。
            关闭 LLM 时可使用规则切分；开启后请求失败会保留旧产物并提示重试。
          </p>
          <p class="p">
            语义整理和翻译一样使用纯文本协议。请求只发送带时间的短语/词级行，不再额外发送没有时间信息的拼接原文。
            输入行形如 <code>0.00-2.42: good morning today we are taking a bullet train</code>；模型输出必须带序号，形如 <code>1. 0.00-2.42: …</code>；长停顿用 <code># 停顿</code> 注释提示。输出中的空格差异、空行和小幅时间偏差会兼容并警告；序号缺失、重复或错位才会定向重试。
            模型直接返回编号时间轴文本，每行“序号. 开始秒-结束秒: 原文片段”；序号从 1 连续、片段非空，起止时间贴近语音，最终时间递增且不重叠。
            换行是条目分隔边界；ASR 短语文本会在进入本步骤前归一为单行，所以正文里的相似文字不会被误认为新条目。
            语义整理一次提供全文，允许结合全文语境和常识纠正错词、漏词、人名、数字、币种、单位及否定表达，清理识别噪声并调整句界，不要求照抄识别稿。
            数值、单位、否定等变化会记录位置与前后内容供复核；词形匹配不足或少量删词也只提示。程序重点检查编号、有效时间、明显大段遗漏或台词搬移、重复抄写，并保留真实长静音。质量失败最多定向重试一次，旧产物保留。
          </p>
          <p class="p">
            真实长停顿前的半句可以保留；只有词形可疑的口语接续会提示复核，极短碎片、密度异常与时间冲突仍会检查。
            语义整理全文超预算时提示核对模型容量；翻译按 token 预算装入连续字幕行，默认再限制每窗最多 100 行，保留前后参考与术语交接；设置为 0 时只按 token 自适应分窗。
            整理和翻译可选择低思考强度（low）：已适配接口会应用本步骤的思考参数，必要时移除该接口不兼容的字段，其余自定义参数保留。未适配接口保留 JSON 思考参数，提示词要求直接完成任务，不能保证降低思考强度。表单与请求预览显示实际使用的档位和字段变化；选择“跟随自定义 JSON / 服务商默认”可保留所有原参数。low 是轻量思考，不等于关闭思考，也不保证固定耗时。
          </p>
          <p class="p">
            无论选择哪种思考模式，每次整理或翻译请求都要求只返回一份最终结果。程序在流式接收时检查编号和格式，并限制异常体积及持续重复；异常候选不会写入产物。输出校验失败需要重试时，使用新的独立请求，次数有限，不接着异常输出反复自审；最终仍须通过文字、编号和时间校验，失败时保留旧产物。
            设置页的“请求时限（秒）”对这两个步骤是单次请求的总时限，计入等待首字节、思考和持续流式输出；收到新内容不会重置计时，每次新请求分别计时。达到总时限后报告失败，不自动重试或切换模型；会关闭本地连接，但不能确认服务商已停止计算或计费。
          </p>
          <p class="p">
            单次上下文预算默认0.2M，设置页最高可调到1M；系统为提示词和完整输出预留空间，预算须与模型真实容量匹配。
            语义整理和翻译显示“预计进度”：没有相近历史时，整个步骤默认按 10 分钟估算，多窗口按原文长度分摊。
            准备占 1%，等待响应/深度思考占 60%，模型输出占 38%，实际收尾占 1%；收到正文后才进入输出阶段，成功后才到 100%。
            有历史时，使用同模型、同任务、相近输入规模最近最多 20 条正常记录，按原文长度换算单位耗时；两端各去掉三分之一（向下取整），平均剩余记录。一两条记录直接取平均。
            没有思考流回调时，预计进度也会刷新；超出当前阶段预估后缓慢推进并显示已用时间，重试时保留已有进度。这两种情况下暂不显示倒计时。
            下载进度按音视频合计字节量，剩余时间为剩余字节数除以本次累计平均下载速度，不再使用近期滑动窗口。实际暂停不计时。
            语音转文字在模型加载、音频准备和首批结果返回前显示具体阶段及已用时间，不显示无法测量的百分比。开始返回结果后按已识别的音频时间推进，分批跳动是正常现象；仅在有新结果时更新累计平均速度，批次之间倒计时，估计耗尽则暂时隐藏剩余时间。
            纠错在语义整理或原文校对时完成，本地分句和时间校正保留模型的纠错文字。翻译以本次整理定稿为准，保持相同句数、编号和时间，不把邻句信息移到当前编号。设置页可以查看历史耗时。
          </p>
        </n-collapse-item>
        <n-collapse-item title="错误信息怎么看？" name="error">
          <p class="p">
