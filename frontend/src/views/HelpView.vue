      <p class="p">发布设置唯一决定是否上传、是否投稿及新稿或原稿目标。更新原稿须明确选择BV、对应分P的替换版本与同步字段；只同步文案或章节时关闭「替换视频文件」，会复用已上传的版本与时间轴，不要求重新制作。已有BV不会自动升级仅制作或草稿终点。上传后等待确认的任务仅上传文件，由你在发布页明确提交。继续旧任务保留它原来的交付授权，后改的设置不会让旧任务自动投稿。</p>
      <p class="p">没有发布记录或已确认发布任务的项目，首次发布默认创建新稿，套用模板后可直接批量运行，无需逐个进入发布页选择。这个默认不会保存为永久项目覆盖；产生本地草稿、上传或投稿记录后，再按当前设置开始新执行须明确选择新稿或原稿。已有中断任务应继续原任务，沿用原范围与回执。主动清空目标仍需重新选择，未知回执必须先核对；仅制作不需要稿件目标。</p>
      <p class="p">一个视频文件对应一个分P；加入多个成片版本，会发布为同一个BV下的多个分P，不自动切片。P1、P2等卡片同时显示B站分P名称、对应版本和实际文件，上移、下移只调整发布顺序，改名只修改B站显示名称。新建草稿和保存资料都不会开始上传；核对后点击「上传并投稿」。已投稿记录优先展示进度与回执，视频和稿件快照可展开查看；本地文件是否仍存在不代表B站上传或审核状态。</p>
      <p class="p">项目卡片可直接选择模板或「应用最新设置」，先比较变化，确认后替换项目基础值，并保留项目单独设置。交付终点、账号、合集和分P顺序仍在项目对应步骤保存。勾选多个项目后使用「批量运行…」，会按实际保存的账号、合集与小节自动分组；同一合集组内按确认顺序逐项执行，其他合集与独立项目分别推进。首次检查自动补齐原视频发布日期并据此排序，也可在组内上移、下移；重新检查会重试补齐日期并保留已调整顺序。只有同一合集有多个项目且仍缺日期时才提醒核对；补齐失败不影响继续检查，已保存批次沿用确认顺序。预检核对各项目的原有终点、分P与实际制作步骤，不增加另一份批量设置。</p>
      <p class="p">例如三个同合集视频与两个零散视频可以一起勾选：三个视频组成保序组，两个视频独立执行。仅制作、准备草稿或上传后等待确认的项目保持各自终点；自动投稿须核对授权后确认。同合集前项审核通过并确认入合集后再推进后项，最后回读检查排列。某一组失败或结果不明时保留回执并暂停该组，其余组继续；在「批量运行记录」中可按组或整批暂停、停止及检查恢复。关闭页面不会中断；服务重启后须检查并确认继续。</p>
      <p class="p">未上传草稿会在制作完成后重新绑定已确认版本的最新成片，已经上传的清单继续原记录。已有原BV只核对审核、合集与排列时，不替换视频或重新投稿；多个候选草稿需先在发布页处理为明确目标。需要替换原BV视频时，到项目「发布到B站」保存原稿目标、替换分P和同步范围，预检后确认执行；章节按新成片时间轴处理。另发新稿会创建新BV；需要保留原BV时选择更新原稿。旧「顺序发布批次」保留历史记录与恢复入口。</p>
      <p class="p">「全部发布记录」分为常用记录、已归档和回收的草稿。纯本地、未上传草稿可以回收；已有上传或BV的记录可归档，不删除平台稿件，也不解除防重复投稿保护。两者均保留数据库资料、成片和回执，可在对应区域恢复，恢复后才能编辑或继续发布；这里的回收区不是系统回收站。运行中或结果不明的记录需先结束任务、核对结果后管理。</p>
      <p class="p">只提取音轨时关闭「人声/背景分离」。语义整理完成后即可进入「字幕与配音」校对原文和时间，导出原文不需要翻译。有译文后可校对译文、生成配音。是否需要字幕和配音由目标成片决定；也可在步骤页单独导出字幕或合成配音，两者互不依赖。上游更新后，「字幕与配音」行的「同步更新」或步骤页的「同步更新并生成」会先更新所需上游，再重新导出字幕并补齐失效配音；仍然有效的句子会复用。</p>
      <p class="p">配音运行中，选择其他句子后可点击「加入待配音…」，确认目标槽后排入同一任务；也可勾选多句加入。当前句继续合成，新增句优先依次执行，再继续原任务。正在合成或已等待的句子不会重复加入。追加使用本轮项目参数与已保存的本句设置；准备范围、停止或最终排布期间暂不接收新句子，已生成的声音保留。</p>
      <p class="p">句子列表切换筛选会保留各自的阅读位置。「配音待更新」表示当前文字或设置尚未应用到声音；「成片待更新」则与所选成片逐句对照，仅标记实际字幕、声音或播放位置的差异。合成成片页的「检查与更新成片」集中展示字幕、声音、上屏评论、剪辑与呈现设置的前后变化；时间轴不变时可检查全部局部改动、添加更新版本，保存后沿用统一生成和自动流程。修改过时间或移除评论时会同时带入已知的新旧范围。旧成片没有逐句记录时，手工编辑过的句子显示为「成片待核对」，可明确选择这些句子修订，或完整生成一次建立可靠对照。剪辑时间轴、全局呈现或跨句声音处理变化通过完整更新应用。</p>
      <p class="p">每句铅笔打开「文字与时间」：播放排布页对照原始时间、自动方案与最终播放时间，可保存人工起点、延长字幕预留或恢复自动；邻句会避让人工位置。调整位置不重做声音、不新建配音槽，原文和译文一起移动。源稿校对页用于修改文字和源时间，保留上游原稿；朗读跟随译文时，修改译文需重新生成本句配音；自定义朗读独立保留。</p>
      <p class="p">「重新排布（不改声音）」按当前已选音频和保存的设置重新计算，不调用模型、不改槽或满意标记；相同输入得到相同位置是正常结果。自动排布关闭时只检查源时间和人工位置。需要精确移动一句，用侧栏保存人工起点；邻句自动避让，原文和译文同步。勾选只限定哪些句子重新合成。排布先在人工位置、原声、静音和缺音频障碍之间尝试完整原速排布，每句始终受最大位移限制；原速仍放不下时，才使用默认9句的缩时分析窗口。补齐音频后联动范围可能变化，邻句声音不会因此重新生成。</p>
      <p class="p">每句有效音频写完并选用后，工作台即按真实时长更新排布；整批正常结束后，再对排布仍放不下的句子有限缩时，每次返回后重排。合成请求超时或部分失败时保留已有音频并更新排布报告，不在失败收尾继续调用模型。尚无有效音频的句子先保留源时间，补齐后再准确协调。</p>
      <p class="p">「上屏评论」工作区的「评论处理流程」展示获取原文、评论评分、按需翻译和上屏方案。评分与翻译显示本次处理条数、缓存复用、当前批次及模型等待、思考、接收、校验和纠错阶段；已处理含失败或跳过，成功数量另列。获取评论没有平台实时百分比，只显示联网状态、上次快照、本次上限和真实耗时。手动可只执行某个操作，也可用「准备目标数量评论」衔接必要处理；自动流程复用同一准备逻辑并按确认计划继续。</p>
      <p class="p">总览的评论准备阶段也显示同一份实时状态，可直接进入评论工作区或当前LLM对话。进度与完整资料分开读取，只有新结果保存后才刷新评论列表；运行时保持阅读顺序与未保存草稿。错误、中断及重试不会清空已完成结果，详细原因仍可在逐条状态和诊断中查看。</p>
      <p class="p">列表简要显示实际播放范围、自动或人工位移以及实际缩时因子。新发生的自动缩时会保留同槽的完整声音记录，在侧栏应用缩短前或缩短后的记录，不调用模型、不改变选槽和本句参数；声音改变后需重新确认满意。没有保存原音频的旧缩时结果无法只凭因子数值还原，可选择已有历史配音槽。</p>
      <p class="p">视频上方可切换原文、译文、双语字幕或关闭；直接预览已保存的文字与时间，无需导出或配音。双语默认译文在上、原文在下，顺序沿用导出设置。字幕工作区可拖动进度条定位画面，松开后更新烧录预览；也可输入精确秒数或选择句子，不会修改字幕时间或播放器位置。</p>
      <p class="p">试听时视频原声由独立的人声／背景音轨接管。播放器小喇叭和「监听总音量」控制实际所有试听声轨，只影响本机；「仅听人声」即时作用于单句和连续播放，不改变声源选择。下方「人声／背景」调节项目混音，停止拖动后自动保存，供后续配音成片使用，版本专用设置仍优先。快速试听不模拟整轨响度校准和背景避让，最终听感请用合成页的试片核对。若媒体加载或播放失败，页面会保留错误说明；再次点击「连续播放」、视频播放按钮或本句试听会重新加载失败音轨，不需要重新合成。已正常加载的音轨保留，后台不会无限自动重试。</p>
      <p class="p">各页面的视频预览共用键盘操作：点击画面或用 Tab 聚焦播放器后，←/→ 后退/前进 5 秒；暂停时按逗号/句号或控制条的上一帧/下一帧按源帧率移动，用于精确标记删除起止点。↑/↓ 每次调整监听总音量 5%，空格或 K 播放/暂停，M 静音/恢复，F 全屏/恢复，Home/End 跳到开头/结尾。音量只影响本机试听。焦点移到播放器外或在输入框、下拉框中操作时，快捷键不接管；按钮与音量滑条保留自己的键盘操作。</p>
      <p class="p">「字幕与配音」分为「校对与配音」和「字幕工作区」。字幕工作区在页面内并排显示烧录效果与设置，统一调整字体、颜色、描边、底距、双语顺序和导出类型；停止调整后自动用草稿渲染一帧，无需先导出或配音。切换这两个标签保留草稿，点击「保存字幕设置」才生效，再导出字幕或生成带烧录字幕的成品。合成页的「预览与调整字幕」直达同一工作区，不再重复编辑。SRT 不保存样式，播放器字幕只用于核对文字与时间，不等于开启烧录。</p>
      <p class="p">合成成片页顶部「选择成品方案」只定位，不启动任务。声音、对话字幕、观众评论是三个独立选项：选择当前组合后可先试片，或「加入本次清单」，再继续添加其他组合。「生成清单成品」只处理清单里的方案，可同时生成含评论与不含评论的成品；同组合再次生成会在成功后覆盖当前成品，失败或取消保留原文件。三项都关闭、未启用剪辑且「最终成片响度」为「保持混音音量」时直接使用原片。已有组合直接显示，可一键加入重生成；升级前的历史文件不会自动删除。</p>
      <p class="p">「合成成片 → 成片剪辑」按原视频时间为当前版本标记广告等不要的片段，可添加多段、逐段启停和备注，也可从已生成的旧成片导入范围。恢复某段只需停用或移除对应范围；保存后重新生成当前版本，旧成片保持不变。画面、声音、烧录字幕和评论一起裁剪，源视频、识别、翻译、逐句配音和源轴 SRT 不变，章节按对应成片快照换算时间。未建立版本级方案时兼容回退项目默认方案；排队任务在开始执行前冻结本次范围，运行中保存的修改供下次使用。换源后需核对并重新绑定范围。当前为人工指定范围，AI 自动分析尚未接入。</p>
      <p class="p">在「设置 → 制作与发布」编辑全局默认和系列模板；模型连接、密钥与环境位于「模型与服务」，并行度、存储与显示偏好位于「运行与存储」。新项目保存创建时的全局或模板基础值，项目单独设置优先；之后修改全局或模板不会自动改变已有项目，也不会因此要求重跑。项目总览可点击「应用最新设置」，项目列表勾选后可批量选择要应用的来源；先查看旧值、新值和影响步骤，确认后才更新基础值，项目覆盖保留。同值、关闭、0 和空合集也是明确设置。</p>
      <p class="p">各页的配置来源标识使用同一套文字和颜色：全局默认为蓝色、系列模板为紫色、项目设置为青绿色，版本、本句和稿件设置另有固定颜色。悬停可查看具体模板、版本或基础值说明；项目基础来源保留创建或上次应用时的值，来源颜色不代表实时跟随或保存状态。编辑与恢复操作后，标识随草稿更新，仍需保存才生效。</p>
      <p class="p">每项参数旁的小回转箭头用于恢复，悬停可查看恢复到哪一层；已继承、没有可撤销修改或受运行锁定时灰显。全局默认没有上级设置，「撤销修改」回到当前已保存的全局值并保留其他修改；保存后新值成为下次撤销的基准。模板的「恢复继承」移除模板覆盖，重新跟随全局。项目的「恢复项目基础值」移除制作参数覆盖，回到创建或上次应用时保存的值，不读取最新来源；连接、代理和超时等共享服务用于之后的调用，对应「恢复服务设置」使用共享服务当前值。版本参数与本句设置可恢复为项目共同参数；版本名称和声音、字幕、评论开关则撤销到此版本已保存的值。恢复先用于当前编辑，仍需通过所在表单的保存或确认按钮提交。</p>
      <p class="p">项目空间默认显示「当前项目」。完成或暂时搁置的项目可在「更多」中归档，勾选后也可批量归档。切换「已归档」可查看产物、日志与发布记录，并恢复项目。归档保留全部文件和项目设置，不释放磁盘空间；运行或上传中的项目需等待结束。恢复后才能编辑、制作或重新发布，现有稿件的审核结果仍可查询。归档期间修改全局或模板，不改变该项目保存的基础值。</p>
      <p class="p">成片版本在合成步骤维护，可分别设置配音、字幕、评论及各自的呈现差异。运行项目时根据已保存发布规则选择分P顺序与执行终点，在抽屉核对成品、账号、合集和可见范围后确认。执行终点与当前状态分开显示，保存自动投稿设置不会开始投稿。项目空间的「批量运行」按各项目实际目标分组，检查通过后确认执行。已有流程稿件沿用其确认清单，继续旧任务不会被后来修改的默认终点升级。</p>
      <p class="p">语音转文字生成的 src.srt 是短语级识别原稿，可直接下载。「字幕工作区」底部可导出 source.srt 原文、trans.srt 译文、bilingual.srt 双语，并查看文件位置。文件旁的“预览”切回校对播放器，核对实际导出结果，文件过期后自动切回当前文字。最短显示时长用于导出和烧录预览，利用空隙延长；手动修改过时间的句子始终使用所设时间，换行交给播放器处理。</p>
      <p class="p">声音分三层调整：播放器的本机监听音量不改变制作结果；人声与背景平衡决定讲话是否清楚；统一输出响度决定不同项目的总体音量是否接近。先用试片调好人声与背景比例，再用相同响度目标校准成片。LUFS 相近不能保证人声与背景协调，仍需试听。</p>
      <p class="p">成片版本和最近试片下方的「声音测量与原片对照」显示同一源时段、同一剪辑保留范围的原片与输出测量，以及生成时的统一目标。原片只作对照，不作为追随目标；原片偏轻或偏响不应带偏成片。悬停指标名称、数值和设置区域，或点击问号，可查看解释与建议。短于 60 秒的响度范围仅作统计参考。</p>
      <p class="p">统一响度模式先处理完整成片音轨再截取试片；保留动态模式的试片沿用完整混音增益，局部短片自身的响度不要求等于整片目标。有完整处理基准时可展开查看编码前的整片测量，不与当前短片混用。展开逐句明细可定位人工增益、句间均衡、静音和峰值风险；逐句使用源时间，静音区间使用成品时间。旧报告会明确标记，修改设置后需重新生成；数值不能单独证明存在可闻失真。</p>
      <p class="p">希望不同项目响度一致时，在全局或共同模板中启用「统一响度」，使用相同目标（可先保持 −16 LUFS、真峰值上限 −1.5 dBTP），再主动应用到已有项目。项目与版本单独设置优先，需核对并按需恢复继承；不会自动覆盖精调或重做旧成品。−16 LUFS 是产品预设，不是 B 站官方标准。</p>
      <p class="p">使用原声参考配音或混入背景音时才需要相应的分离音轨。背景音量设为 0 可省略背景音；开启字幕烧录时才要求指定的字幕文件。外挂字幕从字幕导出目录取用。</p>
