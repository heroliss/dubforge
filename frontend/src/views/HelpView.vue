      <p class="p">各页的配置来源标识使用同一套文字和颜色：全局默认为蓝色、系列模板为紫色、项目设置为青绿色，版本、本句和稿件设置另有固定颜色。悬停可查看具体模板或版本名称；来源颜色不代表保存状态。编辑与恢复继承后，标识随草稿更新，仍需保存才生效。</p>
