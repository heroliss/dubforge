      <p class="p">YouTube 默认只采集评论数；在「上屏评论」阶段点击「获取热门评论」，可取 1–500 条平台热门顶层评论，不含回复，实际可能少于请求数。本次数量初始采用项目采集上限，修改输入框不保存项目设置。评论列表支持对照原文，长文按需展开，悬停分数可看判断理由；每条的「翻译本条」只补译该条，不改变是否上屏。</p>
